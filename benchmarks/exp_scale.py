"""
benchmarks.exp_scale | Layer: BENCHMARK
Measure how the matcher behaves as the dictionary grows.

The labelled benchmark has 793 entries. That is enough to measure ACCURACY but says
nothing about behaviour at enterprise glossary size, where dense retrieval cost is
linear in the number of entries for the exact store.

This script grows the corpus with synthetic distractor entries while keeping the same
793 gold entries and the same 793 queries, so accuracy stays comparable and any drop is
attributable to the larger candidate pool rather than to a different task. It compares
the exact in-memory store against the HNSW store at each size.

Distractors are generated by recombining real vocabulary from the actual dictionary
rather than from random noise: random text would embed into a region far from every
query and would make retrieval look artificially easy as the corpus grew.

Usage:
    python benchmarks/exp_scale.py --sizes 793 10000 50000 100000
"""

from __future__ import annotations

import argparse
import json
import random
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from eval_harness import RESULTS, Dataset, DictEntry, score_rankings
from exp_query_repr import VARIANTS

BGE_PREFIX = "Represent this sentence for searching relevant passages: "


def make_distractors(entries: list[DictEntry], target: int, seed: int = 0) -> list[DictEntry]:
    """Recombine real vocabulary into plausible-but-wrong dictionary entries."""
    rng = random.Random(seed)
    name_tokens = [t for e in entries for t in e.business_name.split() if t]
    desc_tokens = [t for e in entries for t in e.description.split() if t]
    domains = sorted({e.domain for e in entries})
    types = sorted({e.data_type for e in entries})

    out: list[DictEntry] = []
    n_needed = target - len(entries)
    for i in range(max(0, n_needed)):
        name = " ".join(rng.choice(name_tokens) for _ in range(rng.randint(2, 5)))
        desc = (
            " ".join(rng.choice(desc_tokens) for _ in range(rng.randint(6, 18)))
            if desc_tokens
            else ""
        )
        out.append(
            DictEntry(
                id=f"distractor::{i}",
                business_name=name,
                logical_name="",
                description=desc,
                data_type=rng.choice(types),
                domain=rng.choice(domains),
            )
        )
    return out


def run(entries, queries, golds, model, backend: str, top_k: int):
    """Index `entries` in `backend` and run all queries; return metrics."""
    from nexus_matcher.domain.ports.vector_store import VectorDocument, VectorStoreConfig

    dim = model.get_sentence_embedding_dimension()
    corpus = [e.searchable_text("business+desc") for e in entries]

    t0 = time.perf_counter()
    doc_emb = model.encode(
        corpus, batch_size=256, normalize_embeddings=True, show_progress_bar=False
    ).astype(np.float32)
    encode_s = time.perf_counter() - t0

    if backend == "memory":
        from nexus_matcher.infrastructure.adapters.vector_stores.memory import (
            InMemoryVectorStore as Store,
        )

        store = Store(VectorStoreConfig(collection_name="d", dimension=dim))
    else:
        from nexus_matcher.infrastructure.adapters.vector_stores.hnsw import (
            HnswVectorStore as Store,
        )

        store = Store(VectorStoreConfig(collection_name="d", dimension=dim))

    t0 = time.perf_counter()
    store.upsert(
        [VectorDocument(id=e.id, embedding=doc_emb[i], payload={}) for i, e in enumerate(entries)]
    )
    index_s = time.perf_counter() - t0

    q_emb = model.encode(
        [BGE_PREFIX + VARIANTS["context"](q) for q in queries],
        batch_size=256,
        normalize_embeddings=True,
        show_progress_bar=False,
    ).astype(np.float32)

    t0 = time.perf_counter()
    rankings = []
    for vec in q_emb:
        res = store.search(vec, top_k=top_k)
        rankings.append([r.id for r in res.unwrap()] if res.is_success else [])
    search_s = time.perf_counter() - t0

    s = score_rankings(rankings, golds, ks=(1, 5, 10))
    return {
        "p_at_1": s["p_at_1"],
        "mrr_at_10": s["mrr_at_10"],
        "recall_at_10": s["recall"][10],
        "encode_seconds": encode_s,
        "index_seconds": index_s,
        "search_seconds": search_s,
        "queries_per_sec": len(queries) / search_s if search_s else 0.0,
        "ms_per_query": search_s / len(queries) * 1000 if queries else 0.0,
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--benchmark", default="combined")
    ap.add_argument("--model", default="BAAI/bge-small-en-v1.5")
    ap.add_argument("--sizes", nargs="*", type=int, default=[793, 10_000, 50_000, 100_000])
    ap.add_argument("--top-k", type=int, default=10)
    ap.add_argument("--backends", nargs="*", default=["memory", "hnsw"])
    args = ap.parse_args()

    from sentence_transformers import SentenceTransformer

    ds = Dataset.load(args.benchmark)
    golds = [q.gold_id for q in ds.queries]
    model = SentenceTransformer(args.model, device="cpu")

    print(f"\nScale sweep on '{ds.name}' ({len(ds.queries)} queries, gold entries always present)")
    print(
        f"  {'entries':>8s} {'backend':>8s} {'P@1':>7s} {'MRR@10':>7s} {'R@10':>7s} "
        f"{'index_s':>8s} {'ms/query':>9s} {'qps':>9s}"
    )
    print(f"  {'-' * 8} {'-' * 8} {'-' * 7} {'-' * 7} {'-' * 7} {'-' * 8} {'-' * 9} {'-' * 9}")

    out: list[dict] = []
    for size in args.sizes:
        entries = list(ds.entries) + make_distractors(list(ds.entries), size)
        for backend in args.backends:
            try:
                m = run(entries, ds.queries, golds, model, backend, args.top_k)
            except Exception as exc:
                print(f"  {len(entries):8d} {backend:>8s}  FAILED: {type(exc).__name__}: {exc}")
                continue
            print(
                f"  {len(entries):8d} {backend:>8s} {m['p_at_1']:7.4f} {m['mrr_at_10']:7.4f} "
                f"{m['recall_at_10']:7.4f} {m['index_seconds']:8.1f} "
                f"{m['ms_per_query']:9.3f} {m['queries_per_sec']:9.1f}"
            )
            out.append({"n_entries": len(entries), "backend": backend, **m})

    RESULTS.mkdir(parents=True, exist_ok=True)
    p = RESULTS / f"exp_scale_{ds.name}.json"
    p.write_text(
        json.dumps({"benchmark": ds.name, "model": args.model, "runs": out}, indent=2),
        encoding="utf-8",
    )
    print(f"\nSaved -> {p}")


if __name__ == "__main__":
    main()
